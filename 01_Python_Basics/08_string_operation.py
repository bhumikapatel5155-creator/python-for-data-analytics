# String Operations
first_name = "Bhumika"
last_name = "Patel"

# Concatenation
full_name = first_name + " " + last_name
print("Full Name:", full_name)

# Length of string
print("Length:", len(full_name))

# Indexing
print("First Character:", full_name[0])
print("Last Character:", full_name[-1])

# Slicing
print("First 7 Characters:", full_name[:7])
print("Last 5 Characters:", full_name[-5:])