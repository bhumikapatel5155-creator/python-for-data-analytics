# Type Casting in Python

number_string = "100"

# Convert string to integer
number_int = int(number_string)

# Convert integer to float
number_float = float(number_int)

print("Original value:", number_string)
print("Original type:", type(number_string))

print("\nAfter converting to integer:")
print("Value:", number_int)
print("Type:", type(number_int))

print("\nAfter converting to float:")
print("Value:", number_float)
print("Type:", type(number_float))