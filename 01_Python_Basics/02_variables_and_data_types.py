# Variables and Data Types in Python

name = "Bhumika"
age = 21
cgpa = 7.03
is_student = True

print("Name:", name)
print("Age:", age)
print("CGPA:", cgpa)
print("Student:", is_student)

print("\nData Types:")
print("Name:", type(name))
print("Age:", type(age))
print("CGPA:", type(cgpa))
print("Student:", type(is_student))